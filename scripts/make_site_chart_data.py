"""Export the series the portfolio site charts: daily gross/net equity
curves and the OOS rank-IC series, one CSV. Regenerated by the normal
pipeline run; the site's make_charts.py reads it for the flagship card.
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from alpha.run import run


def main() -> None:
    out = run()
    bt = out["metrics"]["lightgbm"]["bt"]
    ic = out["metrics"]["lightgbm"]["ic_series"].set_index("date")["ic"]

    eq = pd.DataFrame({"gross_equity": bt.equity("gross"),
                       "net_equity": bt.equity("net")})
    eq["oos_ic"] = ic.reindex(eq.index).ffill()
    p = Path("out/site_chart_data.csv")
    p.parent.mkdir(parents=True, exist_ok=True)
    eq.round(6).to_csv(p)
    print(f"wrote {p}  ({len(eq)} days)")
    print(json.dumps({k: out["metrics"][k]["ic_mean"] for k in out["metrics"] if isinstance(out["metrics"][k].get("ic_mean"), (int, float))}, indent=2))


if __name__ == "__main__":
    main()
